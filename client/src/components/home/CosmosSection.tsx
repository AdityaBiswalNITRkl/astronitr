'use client';

import { useEffect, useState } from 'react';
import { api, imageUrl } from '@/lib/api';
import { SectionHeading, Spinner } from '@/components/ui';

type Apod = {
  title?: string;
  url?: string;
  explanation?: string;
  date?: string;
  media_type?: string;
};

export default function CosmosSection() {
  const [apod, setApod] = useState<Apod | null>(null);
  const [fact, setFact] = useState<string | null>(null);
  const [loading, setLoading] = useState(true);

  useEffect(() => {
    Promise.allSettled([
      api<Apod>('/api/nasa/apod'),
      api<string | { fact: string }>('/api/ai/daily-fact'),
    ]).then(([a, f]) => {
      if (a.status === 'fulfilled') setApod(a.value);
      if (f.status === 'fulfilled') {
        const v: any = f.value;
        setFact(typeof v === 'string' ? v : v?.fact ?? '');
      }
      setLoading(false);
    });
  }, []);

  return (
    <section id="cosmos" className="relative z-10 py-24 px-4 sm:px-6">
      <div className="max-w-6xl mx-auto">
        <SectionHeading eyebrow="Live From Space" title="Cosmos Today" />

        {loading ? (
          <Spinner label="Contacting deep space" />
        ) : (
          <div className="grid grid-cols-1 lg:grid-cols-5 gap-6">
            {apod?.url && (
              <div
                className="lg:col-span-3 rounded-2xl overflow-hidden"
                style={{ border: '1px solid rgba(0,240,255,0.15)', background: 'rgba(13,17,38,0.55)' }}
              >
                {/* eslint-disable-next-line @next/next/no-img-element */}
                <img src={imageUrl(apod.url)} alt={apod.title ?? 'NASA APOD'} className="w-full h-72 sm:h-96 object-cover" />
                <div className="p-6">
                  <p className="text-xs tracking-[0.25em] uppercase mb-2" style={{ color: '#00f0ff' }}>
                    NASA · Astronomy Picture of the Day{apod.date ? ` · ${apod.date}` : ''}
                  </p>
                  <h3 className="font-display font-bold text-xl mb-3">{apod.title}</h3>
                  <p className="text-sm leading-relaxed line-clamp-4" style={{ color: 'rgba(226,232,240,0.65)' }}>
                    {apod.explanation}
                  </p>
                </div>
              </div>
            )}

            <div
              className={`rounded-2xl p-8 flex flex-col justify-center ${apod?.url ? 'lg:col-span-2' : 'lg:col-span-5'}`}
              style={{
                border: '1px solid rgba(162,0,255,0.3)',
                background:
                  'linear-gradient(160deg, rgba(162,0,255,0.10), rgba(0,240,255,0.06))',
                backdropFilter: 'blur(12px)',
              }}
            >
              <p className="text-xs tracking-[0.3em] uppercase mb-4" style={{ color: '#c98cff' }}>
                ✨ Cosmic Fact Of The Day
              </p>
              {fact ? (
                <>
                  <p className="text-lg leading-relaxed font-medium" style={{ color: '#e2e8f0' }}>
                    {fact}
                  </p>
                  <p className="mt-6 text-xs tracking-[0.2em] uppercase" style={{ color: 'rgba(226,232,240,0.4)' }}>
                    Generated by AI · refreshed daily
                  </p>
                </>
              ) : (
                <p className="text-sm" style={{ color: 'rgba(226,232,240,0.55)' }}>
                  The daily fact transmission is temporarily offline.
                </p>
              )}
            </div>
          </div>
        )}
      </div>
    </section>
  );
}
